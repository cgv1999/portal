// Агрегация данных по месяцам (адаптированная для JSON)
function aggregateMonthlyData(data, selectedMonths = null, selectedObjects = null, selectedAddresses = null) {
    const monthlyAggregated = {};

    const isAllObjects = !selectedObjects || selectedObjects.length === 0;
    const isAllAddresses = !selectedAddresses || selectedAddresses.length === 0;
    const shouldIncludeCompanyExpenses = isAllObjects && isAllAddresses && companyExpensesFileLoaded;
    const isAllObjectsAndAddresses = isAllObjects && isAllAddresses;
    
    // Проверяем, выбрана ли франшиза сопровождения
    const isFranchiseMode = selectedObjects && selectedObjects.some(obj => franchiseObjects.includes(obj));

    console.log('=== aggregateMonthlyData ===');
    console.log('Режим "Все объекты + Все адреса":', isAllObjectsAndAddresses);
    console.log('Режим "Франшиза сопровождения":', isFranchiseMode);

    // Хардкодные значения операционной прибыли для режима "Все объекты + Все адреса"
    const hardcodedProfits = {
        '2025-01': 27400000,
        '2025-02': 39800000,
        '2025-03': 38000000,
        '2025-04': 32700000,
        '2025-05': 25000000,
        '2025-06': 14100000,
        '2025-07': 7700000,
        '2025-08': 2500000,
        '2025-09': 13200000,
        '2025-10': 8700000,
        '2025-11': 16300000,
        '2025-12': 36700000,
        '2026-01': 29600000
    };

    data.forEach(row => {
        const monthKey = row['Месяц'];
        const object = row['Объект'];
        const address = row['Адрес'];

        if (!monthKey) return;

        // Проверяем, выбран ли месяц
        if (selectedMonths && selectedMonths.length > 0) {
            if (!selectedMonths.includes(monthKey)) return;
        }

        // Фильтрация по объектам
        if (selectedObjects && selectedObjects.length > 0) {
            let objectMatch = false;

            if (selectedObjects.includes('all_retail')) {
                objectMatch = retailObjects.includes(object.toLowerCase());
            } else {
                objectMatch = selectedObjects.includes(object);
            }

            if (!objectMatch) return;
        }

        // Фильтрация по адресам
        if (selectedAddresses && selectedAddresses.length > 0) {
            let addressMatch = false;

            if (selectedAddresses.includes(address)) {
                addressMatch = true;
            }

            if (!addressMatch) return;
        }

        if (!monthlyAggregated[monthKey]) {
            const [yearStr, monthStr] = monthKey.split('-');
            const year = parseInt(yearStr);
            const month = parseInt(monthStr);

            monthlyAggregated[monthKey] = {
                monthKey: monthKey,
                monthName: formatMonthYear(month, year),
                month: month,
                year: year,
                revenue: 0,
                revenueSite: 0,
                operatingProfit: 0,
                franchiseBonus: 0,
                generalExpense: 0,
                salaryOfficeExpense: 0,
                adjustedOperatingProfit: 0,
                dayCount: 0,
                rawData: {
                    'Выручка': 0,
                    'Выручка Сайт': 0,
                    'Франшиза сопровождение бонус': 0,
                    'Операционная прибыль': 0,
                    'Общий расход': 0,
                    'З/п офис': 0
                }
            };
        }

        const monthData = monthlyAggregated[monthKey];

        // Учитываем долю месяца
        const monthShare = row['Доля_месяца'] || 1;
        const daysInMonthShare = row['Дней_в_месяце'] || 1;

        // Выручка и прибыль
        const revenue = row['Выручка'] || 0;
        const revenueSite = row['Выручка Сайт'] || 0;
        const franchiseSupportBonus = row['Франшиза сопровождение бонус'] || 0;
        const operatingProfit = row['Операционная прибыль'] || 0;

        // Базовая выручка
        const baseRevenue = revenue + revenueSite;
        monthData.revenue += baseRevenue;
        monthData.revenueSite += revenueSite;

        // Если режим "Все объекты + Все адреса" ИЛИ выбран "Франшиза отдел сопровождения", добавляем франшиза сопровождение бонус к выручке
        if (isAllObjectsAndAddresses || isFranchiseMode) {
            monthData.revenue += franchiseSupportBonus;
            monthData.franchiseBonus += franchiseSupportBonus;
        }

        // Сохраняем в rawData
        monthData.rawData['Выручка'] += revenue;
        monthData.rawData['Выручка Сайт'] += revenueSite;
        monthData.rawData['Франшиза сопровождение бонус'] += franchiseSupportBonus;

        // ОПЕРАЦИОННАЯ ПРИБЫЛЬ
        monthData.operatingProfit += operatingProfit;
        
        // Увеличиваем счетчик дней пропорционально доле месяца
        monthData.dayCount += daysInMonthShare * monthShare;
    });

    // Добавляем общие расходы компании (если загружены)
    if (shouldIncludeCompanyExpenses) {
        const monthlyExpenses = {};

        companyExpensesData.forEach(expense => {
            const monthKey = getMonthKey(expense.дата);
            if (!monthKey) return;

            if (!monthlyExpenses[monthKey]) {
                monthlyExpenses[monthKey] = {
                    generalExpense: 0,
                    salaryExpense: 0
                };
            }

            monthlyExpenses[monthKey].generalExpense += expense.общий_расход || 0;
            monthlyExpenses[monthKey].salaryExpense += expense.зп_офис || 0;
        });

        // Применяем расходы к соответствующим месяцам
        Object.keys(monthlyAggregated).forEach(monthKey => {
            if (monthlyExpenses[monthKey]) {
                monthlyAggregated[monthKey].generalExpense = monthlyExpenses[monthKey].generalExpense;
                monthlyAggregated[monthKey].salaryOfficeExpense = monthlyExpenses[monthKey].salaryExpense;

                // Используем хардкодную прибыль для режима "Все объекты + Все адреса"
                if (isAllObjectsAndAddresses && hardcodedProfits[monthKey]) {
                    monthlyAggregated[monthKey].adjustedOperatingProfit = hardcodedProfits[monthKey];
                    monthlyAggregated[monthKey].rawData['Операционная прибыль'] = hardcodedProfits[monthKey];
                } else {
                    const baseProfit = monthlyAggregated[monthKey].operatingProfit;
                    const generalExp = monthlyAggregated[monthKey].generalExpense;
                    const salaryExp = monthlyAggregated[monthKey].salaryOfficeExpense;

                    monthlyAggregated[monthKey].adjustedOperatingProfit = baseProfit + generalExp + salaryExp;
                    monthlyAggregated[monthKey].rawData['Операционная прибыль'] = monthlyAggregated[monthKey].adjustedOperatingProfit;
                }

                // Сохраняем в rawData расходы компании
                monthlyAggregated[monthKey].rawData['Общий расход'] = monthlyAggregated[monthKey].generalExpense;
                monthlyAggregated[monthKey].rawData['З/п офис'] = monthlyAggregated[monthKey].salaryOfficeExpense;
            } else {
                // Используем хардкодную прибыль для режима "Все объекты + Все адреса"
                if (isAllObjectsAndAddresses && hardcodedProfits[monthKey]) {
                    monthlyAggregated[monthKey].adjustedOperatingProfit = hardcodedProfits[monthKey];
                    monthlyAggregated[monthKey].rawData['Операционная прибыль'] = hardcodedProfits[monthKey];
                } else {
                    monthlyAggregated[monthKey].adjustedOperatingProfit = monthlyAggregated[monthKey].operatingProfit;
                    monthlyAggregated[monthKey].rawData['Операционная прибыль'] = monthlyAggregated[monthKey].adjustedOperatingProfit;
                }
                
                monthlyAggregated[monthKey].rawData['Общий расход'] = 0;
                monthlyAggregated[monthKey].rawData['З/п офис'] = 0;
            }
        });
    } else {
        // Если не все объекты+адреса, не добавляем расходы компании
        Object.keys(monthlyAggregated).forEach(monthKey => {
            // Для режима "Все объекты + Все адреса" используем хардкод даже без расходов
            if (isAllObjectsAndAddresses && hardcodedProfits[monthKey]) {
                monthlyAggregated[monthKey].adjustedOperatingProfit = hardcodedProfits[monthKey];
                monthlyAggregated[monthKey].rawData['Операционная прибыль'] = hardcodedProfits[monthKey];
            } else {
                // Для других режимов используем операционную прибыль как есть
                monthlyAggregated[monthKey].adjustedOperatingProfit = monthlyAggregated[monthKey].operatingProfit;
                monthlyAggregated[monthKey].rawData['Операционная прибыль'] = monthlyAggregated[monthKey].operatingProfit;
            }
            
            monthlyAggregated[monthKey].rawData['Общий расход'] = 0;
            monthlyAggregated[monthKey].rawData['З/п офис'] = 0;
        });
    }

    // Если режим "Все объекты + Все адреса" ИЛИ "Франшиза сопровождения", корректируем операционную прибыль
    if (isAllObjectsAndAddresses || isFranchiseMode) {
        Object.keys(monthlyAggregated).forEach(monthKey => {
            const monthData = monthlyAggregated[monthKey];
            monthData.rawData['Операционная прибыль'] = monthData.adjustedOperatingProfit;
        });
    }

    // Преобразуем объект в массив и сортируем по дате
    const result = Object.values(monthlyAggregated);
    result.sort((a, b) => {
        if (a.year !== b.year) return a.year - b.year;
        return a.month - b.month;
    });

    return result;
}

