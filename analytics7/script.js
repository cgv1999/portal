// Функция для парсинга даты из строки в формате DD.MM.YYYY
function parseDate(dateStr) {
    try {
        if (!dateStr) return null;
        const [day, month, year] = dateStr.split('.').map(Number);
        return new Date(year, month - 1, day);
    } catch (e) {
        console.warn('Ошибка парсинга даты:', dateStr, e);
        return null;
    }
}

// Функция для форматирования даты в формат DD.MM.YYYY
function formatDate(dateStr) {
    if (!dateStr) return '';
    try {
        const date = parseDate(dateStr);
        if (!date) return dateStr;

        const day = date.getDate().toString().padStart(2, '0');
        const month = (date.getMonth() + 1).toString().padStart(2, '0');
        const year = date.getFullYear();

        return `${day}.${month}.${year}`;
    } catch (e) {
        console.warn('Ошибка форматирования даты:', dateStr, e);
        return dateStr;
    }
}

// Функция для получения ключа месяца из строки вида "Июн 2023"
function getMonthKeyFromString(monthName) {
    const monthMap = {
        'Янв': '01', 'Фев': '02', 'Мар': '03', 'Апр': '04',
        'Май': '05', 'Июн': '06', 'Июл': '07', 'Авг': '08',
        'Сен': '09', 'Окт': '10', 'Ноя': '11', 'Дек': '12'
    };
    
    try {
        const parts = monthName.split(' ');
        if (parts.length === 2) {
            const monthStr = monthMap[parts[0]];
            const year = parts[1];
            if (monthStr && year) {
                return `${year}-${monthStr}`;
            }
        }
    } catch (e) {
        console.warn('Ошибка преобразования месяца:', monthName, e);
    }
    return null;
}

// Функция для форматирования месяца и года в строку
function formatMonthYear(month, year) {
    const monthNames = [
        'Янв', 'Фев', 'Мар', 'Апр', 'Май', 'Июн',
        'Июл', 'Авг', 'Сен', 'Окт', 'Ноя', 'Дек'
    ];
    return `${monthNames[month - 1]} ${year}`;
}

// Функция для получения ключа месяца (YYYY-MM) из строки даты
function getMonthKey(dateStr) {
    const monthKey = getMonthKeyFromString(dateStr);
    return monthKey;
}

// Функция для получения ключа месяца из Date объекта
function getMonthKeyFromDate(date) {
    if (!date) return null;
    const year = date.getFullYear();
    const month = date.getMonth() + 1;
    return `${year}-${month.toString().padStart(2, '0')}`;
}

// Функция для форматирования валюты
function formatCurrency(value) {
    if (value === 0 || value === null) return '0';
    const absValue = Math.abs(value);
    const roundedValue = Math.round(value);
    
    if (absValue >= 1000000) {
        const inMillions = roundedValue / 1000000;
        if (inMillions >= 1.85 && inMillions < 2.15) {
            return '2M';
        }
        return inMillions.toFixed(1) + 'M';
    } else if (absValue >= 1000) {
        return (roundedValue / 1000).toFixed(0) + 'k';
    }
    return roundedValue.toLocaleString('ru-RU', {
        minimumFractionDigits: 0,
        maximumFractionDigits: 0
    });
}

